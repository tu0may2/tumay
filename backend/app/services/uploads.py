"""Проверка загружаемых файлов до того, как их начнут разбирать.

Книга Excel — это zip-архив, и ограничение на размер загрузки от него
защищает плохо: двести килобайт хорошо сжатых данных разворачиваются в
двести мегабайт. Разбор такого файла съедает память сервера — терминал при
этом не взламывают, его просто кладут, причём случайно это может сделать и
свой человек, приложив не тот файл.

Поэтому смотрим в оглавление архива до распаковки: там заранее записано,
сколько займёт каждый файл. Это дёшево — читается только оглавление — и
ловит случай до того, как под него выделят память.
"""
from __future__ import annotations

import io
import zipfile

#: Во сколько раз содержимому позволено превышать сам файл. Обычная книга
#: Excel сжимается раз в десять-двадцать: разметка XML однообразна. Сотня —
#: это уже не документ, а нарочно собранный архив
MAX_RATIO = 100

#: Потолок на распакованный объём. Самая большая настоящая книга — выгрузка
#: по лицевым счетам за день, это единицы мегабайт
MAX_UNPACKED_BYTES = 256 * 1024 * 1024


class UnsafeUpload(ValueError):
    """Файл, который нельзя разбирать."""


def check_archive(content: bytes, *, max_ratio: int = MAX_RATIO) -> None:
    """Убедиться, что книга не разворачивается в непомерный объём.

    Не-архив пропускаем молча: CSV тоже загружают, и он проверку архива
    проходить не обязан.
    """
    if not content[:2] == b"PK":
        return

    try:
        with zipfile.ZipFile(io.BytesIO(content)) as archive:
            unpacked = sum(item.file_size for item in archive.infolist())
    except zipfile.BadZipFile as exc:
        raise UnsafeUpload("Файл повреждён или это не книга Excel") from exc

    if unpacked > MAX_UNPACKED_BYTES:
        raise UnsafeUpload(
            f"Внутри файла {unpacked // (1024 * 1024)} МБ данных — "
            "это не похоже на выгрузку, разбирать не станем"
        )

    packed = max(len(content), 1)
    if unpacked // packed > max_ratio:
        raise UnsafeUpload(
            f"Файл размером {packed // 1024} КБ разворачивается в "
            f"{unpacked // (1024 * 1024)} МБ. Так сжимаются не документы, "
            "а специально собранные архивы — разбирать не станем"
        )
